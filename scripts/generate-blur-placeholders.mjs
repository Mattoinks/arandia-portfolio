// One-off generator for tiny base64 blur placeholders. These images live in
// /public and are referenced by string path (not static import), so Next.js
// can't auto-generate blurDataURLs for them the way it does for imported
// images — this script produces the equivalent by hand. Re-run whenever one
// of the source images changes.
import { readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const IMAGES = {
  avatar: "public/assets/avatar/1X1-arandia.jpg",
  avatarCutout: "public/assets/avatar/avatar-no-bg.png",
  kalinga: "public/assets/images/projects/kalinga/cover.png",
  infineon: "public/assets/images/projects/infineon/cover.png",
  signa2z: "public/assets/images/projects/signa2z/cover.png",
  "sahari-pay": "public/assets/images/projects/sahari-pay/cover.png",
};

async function main() {
  const entries = await Promise.all(
    Object.entries(IMAGES).map(async ([key, relPath]) => {
      const buf = await readFile(join(root, relPath));
      const resized = await sharp(buf)
        .resize(16, 16, { fit: "inside" })
        .toFormat("webp", { quality: 40 })
        .toBuffer();
      return [key, `data:image/webp;base64,${resized.toString("base64")}`];
    }),
  );

  const out = `// Auto-generated by scripts/generate-blur-placeholders.mjs — do not edit by hand.
export const blurPlaceholders: Record<string, string> = ${JSON.stringify(
    Object.fromEntries(entries),
    null,
    2,
  )};
`;

  await writeFile(join(root, "src/lib/blur-placeholders.ts"), out);
  console.log("Wrote src/lib/blur-placeholders.ts");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
